"use client";

import { useEffect, useRef, useState } from "react";
import type { DragEvent, ReactNode } from "react";
import { captureCoverFrame } from "@/lib/capture-cover-frame";
import { assetReferenceKey, assetUrl, colorFields, colorLabels, isVideoCover, placements, projectAssetReferences, ratios } from "@/lib/studio-types";
import type { BlockDraft, HomeDraft, MediaDraft, ProjectDraft, StudioAsset, StudioProject, StudioState } from "@/lib/studio-types";
import { VideoPairPreview } from "./VideoPairPreview";
import { ProjectIndex } from "./ProjectIndex";

const portfolioPreviewUrl = process.env.NEXT_PUBLIC_PORTFOLIO_PREVIEW_URL ?? "http://localhost:3000";
const mediaFileTypes = {
  image: "image/jpeg,image/png,image/webp,image/gif,image/avif",
  video: "video/mp4,video/webm,video/quicktime,.mp4,.webm,.mov",
};
const libraryFileTypes = `${mediaFileTypes.image},${mediaFileTypes.video}`;
type ProjectTab = "page" | "library" | "settings";

const visibilityFilters = [
  { value: "all", label: "All" },
  { value: "visible", label: "Visible" },
  { value: "hidden", label: "Hidden" },
] as const;
type VisibilityFilter = (typeof visibilityFilters)[number]["value"];

async function api<T>(body?: unknown): Promise<T> {
  const response = await fetch("/api/studio", body === undefined ? { cache: "no-store" } : body instanceof FormData
    ? { method: "POST", body }
    : { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) });
  const value = await response.json();
  if (!response.ok) throw new Error(value.error ?? "Unable to complete this action.");
  return value;
}
function Field({ label, children, hint }: { label: string; children: ReactNode; hint?: string }) {
  return <label className="studio-field"><span>{label}</span>{children}{hint && <small>{hint}</small>}</label>;
}
function Colors({ data, prefix = "", change }: { data: Record<string, unknown>; prefix?: string; change: (key: string, value: string) => void }) {
  return <div className="studio-fields">{colorFields.map((field, index) => {
    const key = prefix ? prefix + field[0].toUpperCase() + field.slice(1) : field;
    const value = String(data[key] ?? "#000000");
    return <Field label={colorLabels[index]} key={key}><div className="studio-color">
      <span className="studio-swatch" style={{ background: /^#[\da-f]{3,8}$/i.test(value) ? value : "transparent" }} />
      <input value={value} onChange={(event) => change(key, event.target.value)} spellCheck={false} />
    </div></Field>;
  })}</div>;
}
function Thumbnail({ id, src, alt = "", type = "image", poster, controls = true }: {
  id: string; src?: string; alt?: string; type?: string; poster?: string; controls?: boolean;
}) {
  if (!src) return <div className="studio-empty-image">No cover yet</div>;
  if (type === "video") return <video src={assetUrl(id, src)} poster={poster ? assetUrl(id, poster) : undefined} controls={controls} playsInline preload="metadata" aria-label={alt || "Video preview"} />;
  // These previews are generated by the local editor endpoint.
  // eslint-disable-next-line @next/next/no-img-element
  return <img src={assetUrl(id, src)} alt={alt} loading="lazy" />;
}

function CoverThumbnail({ id, data, card = false }: { id: string; data: ProjectDraft; card?: boolean }) {
  const isVideo = isVideoCover(data.cover);
  const poster = isVideo ? data.coverPoster : undefined;
  if (card && poster) return <Thumbnail id={id} src={poster} alt={data.coverAlt} />;
  return <Thumbnail id={id} src={data.cover} alt={data.coverAlt} type={isVideo ? "video" : "image"} poster={poster} controls={!card} />;
}

function FileUploadButton({ label, accept, ariaLabel, className = "", onSelect }: {
  label: string;
  accept: string;
  ariaLabel?: string;
  className?: string;
  onSelect: (file: File) => void;
}) {
  const inputRef = useRef<HTMLInputElement>(null);
  return <>
    <button type="button" className={`studio-button ${className}`} aria-label={ariaLabel} onClick={() => inputRef.current?.click()}>{label}</button>
    <input ref={inputRef} type="file" accept={accept} hidden onChange={(event) => {
      const file = event.currentTarget.files?.[0];
      event.currentTarget.value = "";
      if (file) onSelect(file);
    }} />
  </>;
}

function mediaFromAsset(asset: StudioAsset): MediaDraft {
  return { id: crypto.randomUUID(), type: asset.type, src: asset.src, alt: "", aspectRatio: "Default", placement: "full" };
}

function prepareProject(project: StudioProject) {
  const data = { ...project.data, content: project.data.content.map((block) => ({ ...block, id: block.id ?? crypto.randomUUID() })) };
  return { ...project, data };
}

function VideoSyncField({ video, content, index, onChange, onPreview }: {
  video: MediaDraft;
  content: BlockDraft[];
  index: number;
  onChange: (partnerIndex?: number) => void;
  onPreview: (pair: [MediaDraft, MediaDraft]) => void;
}) {
  const candidates = content.flatMap((item, i) => {
    if (i === index || item.type !== "video") return [];
    if (item.syncGroup && item.syncGroup !== video.syncGroup) return [];
    return [{ item, index: i }];
  });
  if (!candidates.length) return null;
  const partner = candidates.find(({ item }) => video.syncGroup && item.syncGroup === video.syncGroup);

  return <div className="studio-video-sync">
    <Field label="Sync start with">
      <select value={partner?.index ?? ""} onChange={(event) => onChange(event.target.value === "" ? undefined : Number(event.target.value))}>
        <option value="">None</option>
        {candidates.map(({ item, index: candidateIndex }) => (
          <option key={candidateIndex} value={candidateIndex}>
            {String(candidateIndex + 1).padStart(2, "0")} / {item.src.split("/").pop()}
          </option>
        ))}
      </select>
    </Field>
    {partner && (
      <button className="studio-button" type="button" onClick={() => {
        onPreview(index < partner.index ? [video, partner.item] : [partner.item, video]);
      }}>Preview pair</button>
    )}
  </div>;
}

export function Studio() {
  const [state, setState] = useState<StudioState | null>(null);
  const [selected, setSelected] = useState<string>("overview");
  const [project, setProject] = useState<StudioProject | null>(null);
  const [home, setHome] = useState<StudioState["home"] | null>(null);
  const [dirty, setDirty] = useState(false);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  const [notice, setNotice] = useState("");
  const [query, setQuery] = useState("");
  const [visibilityFilter, setVisibilityFilter] = useState<VisibilityFilter>("all");
  const [creating, setCreating] = useState(false);
  const [newTitle, setNewTitle] = useState("");
  const [newSlug, setNewSlug] = useState("");
  const [slugEdited, setSlugEdited] = useState(false);
  const [projectTab, setProjectTab] = useState<ProjectTab>("page");
  const [libraryQuery, setLibraryQuery] = useState("");
  const [assetToRemove, setAssetToRemove] = useState<StudioAsset | null>(null);
  const [drag, setDrag] = useState<{ from: number; to?: number; edge?: "before" | "after" } | null>(null);
  const [blockAnnouncement, setBlockAnnouncement] = useState("");
  const [videoPreview, setVideoPreview] = useState<[MediaDraft, MediaDraft] | null>(null);
  const dialogRef = useRef<HTMLDialogElement>(null);
  const removalDialogRef = useRef<HTMLDialogElement>(null);

  useEffect(() => { api<StudioState>().then(setState).catch((e) => setError(e.message)); }, []);
  useEffect(() => {
    if (creating) dialogRef.current?.showModal();
  }, [creating]);
  useEffect(() => {
    if (assetToRemove) removalDialogRef.current?.showModal();
  }, [assetToRemove]);
  useEffect(() => {
    const warn = (event: BeforeUnloadEvent) => { if (dirty) { event.preventDefault(); event.returnValue = ""; } };
    window.addEventListener("beforeunload", warn);
    return () => window.removeEventListener("beforeunload", warn);
  }, [dirty]);

  function switchTo(id: string, source = state) {
    if (busy || !source) return;
    if (dirty && !window.confirm("Discard unsaved changes and switch pages?")) return;
    setSelected(id); setDirty(false); setError(""); setNotice("");
    const nextProject = source.projects.find((p) => id === `project:${p.id}`);
    setProject(nextProject ? prepareProject(nextProject) : null);
    setProjectTab("page"); setLibraryQuery("");
    setDrag(null); setBlockAnnouncement("");
    setHome(id === "home" ? structuredClone(source.home) : null);
  }
  function changeProject(key: string, value: unknown) {
    setProject((current) => {
      if (!current) return current;
      const data = { ...current.data, [key]: value } as ProjectDraft;
      if (key === "cover" && value !== current.data.cover) delete data.coverPoster;
      return { ...current, data };
    });
    setDirty(true); setNotice("");
  }
  function changeHome(key: string, value: unknown) {
    setHome((current) => current ? { ...current, data: { ...current.data, [key]: value } as HomeDraft } : null);
    setDirty(true); setNotice("");
  }
  function changeBlock(index: number, key: string, value: string | boolean) {
    if (!project) return;
    changeProject("content", project.data.content.map((item, i) => i === index ? { ...item, [key]: value } : item));
  }
  function moveBlock(from: number, to: number) {
    if (!project || from === to || from < 0 || to < 0 || from >= project.data.content.length || to >= project.data.content.length) return;
    const content = [...project.data.content];
    const [block] = content.splice(from, 1);
    content.splice(to, 0, block);
    changeProject("content", content);
    setBlockAnnouncement(`${block.type === "caption" ? "Caption" : "Media"} moved to position ${to + 1} of ${content.length}.`);
  }
  function moveWithButton(index: number, direction: -1 | 1, button: HTMLButtonElement) {
    const destination = index + direction;
    const row = button.closest("li");
    moveBlock(index, destination);
    requestAnimationFrame(() => {
      if (button.disabled) row?.querySelector<HTMLButtonElement>(".studio-move:enabled")?.focus({ preventScroll: true });
      row?.scrollIntoView({ block: "nearest" });
    });
  }
  function dragOverBlock(event: DragEvent, index: number) {
    if (!drag || busy) return;
    event.preventDefault();
    event.dataTransfer.dropEffect = "move";
    const bounds = event.currentTarget.getBoundingClientRect();
    const edge = event.clientY < bounds.top + bounds.height / 2 ? "before" : "after";
    if (drag.to !== index || drag.edge !== edge) setDrag({ from: drag.from, to: index, edge });
  }
  function dropBlock(event: DragEvent, index: number) {
    if (!drag || busy) return;
    event.preventDefault();
    const bounds = event.currentTarget.getBoundingClientRect();
    const insertion = index + Number(event.clientY >= bounds.top + bounds.height / 2);
    moveBlock(drag.from, insertion - Number(insertion > drag.from));
    setDrag(null);
  }
  function changeVideoPartner(index: number, partnerIndex?: number) {
    const video = project?.data.content[index];
    if (!project || video?.type !== "video") return;
    const previousGroup = video.syncGroup;
    const syncGroup = partnerIndex === undefined ? undefined : crypto.randomUUID();
    changeProject("content", project.data.content.map((item, i) => {
      if (item.type !== "video") return item;
      if (i === index || i === partnerIndex) return { ...item, syncGroup };
      if (previousGroup && item.syncGroup === previousGroup) return { ...item, syncGroup: undefined };
      return item;
    }));
  }
  function removeBlock(index: number) {
    if (!project) return;
    const block = project.data.content[index];
    const syncGroup = block.type === "video" ? block.syncGroup : undefined;
    const content = project.data.content.filter((_, i) => i !== index);
    changeProject("content", content.map((item) =>
      item.type === "video" && syncGroup && item.syncGroup === syncGroup ? { ...item, syncGroup: undefined } : item
    ));
  }
  function addAsset(asset: StudioAsset) {
    if (!project) return;
    changeProject("content", [...project.data.content, mediaFromAsset(asset)]);
    setNotice(`${asset.name} added to the page draft.`);
  }
  function addCaption() {
    if (!project) return;
    const id = crypto.randomUUID();
    changeProject("content", [...project.data.content, { type: "caption", id }]);
    requestAnimationFrame(() => document.getElementById(`caption-text-${id}`)?.focus());
  }
  async function save() {
    setBusy(true); setError(""); setNotice("");
    try {
      if (project) {
        let data = project.data;
        if (isVideoCover(data.cover) && !data.coverPoster) {
          setNotice("Capturing the first frame of the cover…");
          const still = await captureCoverFrame(assetUrl(project.id, data.cover));
          const form = new FormData();
          form.set("project", project.id);
          form.set("file", still);
          form.set("type", "image");
          const poster = await api<StudioAsset>(form);
          data = { ...data, coverPoster: poster.src };
          setProject({ ...project, data, assets: [...project.assets, poster] });
        }
        const saved = await api<StudioProject>({ action: "project", id: project.id, revision: project.revision, data });
        setProject(prepareProject(saved));
        setState((current) => current ? { ...current, projects: current.projects.map((p) => p.id === saved.id ? saved : p).sort((a, b) => a.data.homeOrder - b.data.homeOrder || a.data.title.localeCompare(b.data.title)) } : null);
      } else if (home) {
        const saved = await api<StudioState["home"]>({ action: "home", revision: home.revision, data: home.data });
        setHome(saved); setState((current) => current ? { ...current, home: saved } : null);
      }
      setDirty(false); setNotice("");
    } catch (e) { setError((e as Error).message); } finally { setBusy(false); }
  }
  async function reload() {
    if (dirty && !window.confirm("Reload from disk and discard your unsaved changes?")) return;
    setBusy(true); setError("");
    try {
      const next = await api<StudioState>(); setState(next);
      const nextProject = next.projects.find((p) => selected === `project:${p.id}`);
      setProject(nextProject ? prepareProject(nextProject) : null);
      setDrag(null); setBlockAnnouncement("");
      setHome(selected === "home" ? structuredClone(next.home) : null); setDirty(false); setNotice("Loaded the latest files.");
    } catch (e) { setError((e as Error).message); } finally { setBusy(false); }
  }
  async function create() {
    setBusy(true); setError("");
    try {
      const created = await api<StudioProject>({ action: "create", title: newTitle, slug: newSlug });
      setState((current) => current ? { ...current, projects: [...current.projects, created] } : null);
      setSelected(`project:${created.id}`); setProject(created); setHome(null); setDirty(false); setCreating(false);
      setProjectTab("settings"); setLibraryQuery("");
      setNewTitle(""); setNewSlug(""); setSlugEdited(false); setNotice("Project created. It will stay hidden until you choose to show it.");
    } catch (e) { setError((e as Error).message); } finally { setBusy(false); }
  }
  async function upload(files: File[], target: "library" | "cover" = "library") {
    if (!files.length || !project) return;
    setBusy(true); setError(""); setNotice("");
    const added: StudioAsset[] = [];
    try {
      for (const file of files) {
        setNotice(`Uploading ${file.name}…`);
        const form = new FormData(); form.set("project", project.id); form.set("file", file);
        added.push(await api<StudioAsset>(form));
      }
      setNotice(target === "library" ? `${added.length} ${added.length === 1 ? "file" : "files"} added to the library.` : "Cover uploaded. Save changes to use it.");
    } catch (e) { setError((e as Error).message); setNotice(""); }
    finally {
      if (added.length) {
        setState((current) => current ? { ...current, projects: current.projects.map((p) => p.id === project.id ? { ...p, assets: [...p.assets, ...added] } : p) } : null);
        setProject((current) => {
          if (current?.id !== project.id) return current;
          if (target === "library") return { ...current, assets: [...current.assets, ...added] };
          const data = { ...current.data, cover: added[0].src };
          delete data.coverPoster;
          return { ...current, assets: [...current.assets, ...added], data };
        });
        if (target !== "library") setDirty(true);
      }
      setBusy(false);
    }
  }
  async function removeAsset() {
    if (!project || !assetToRemove) return;
    const { name, src } = assetToRemove;
    setBusy(true); setError(""); setNotice("");
    try {
      await api({ action: "remove-library-asset", id: project.id, src });
      const withoutAsset = (entry: StudioProject) => ({ ...entry, assets: entry.assets.filter((asset) => asset.src !== src) });
      setState((current) => current ? { ...current, projects: current.projects.map((entry) => entry.id === project.id ? withoutAsset(entry) : entry) } : null);
      setProject((current) => current?.id === project.id ? withoutAsset(current) : current);
      setAssetToRemove(null);
      setNotice(`${name} removed from the library.`);
    } catch (e) { setError((e as Error).message); } finally { setBusy(false); }
  }
  function newProject() {
    if (dirty && !window.confirm("Discard unsaved changes and create a new project?")) return;
    setError(""); setCreating(true);
  }

  const projects = state?.projects ?? [];
  const visibleCount = projects.filter((item) => item.data.published).length;
  const visibilityCounts = { all: projects.length, visible: visibleCount, hidden: projects.length - visibleCount };
  const searchTerm = query.trim().toLowerCase();
  const filtered = projects.filter(({ data }) => {
    const visibility = data.published ? "visible" : "hidden";
    return (visibilityFilter === "all" || visibilityFilter === visibility) &&
      `${data.title} ${data.tags.join(" ")}`.toLowerCase().includes(searchTerm);
  });
  const savedProject = projects.find((item) => item.id === project?.id);
  const savedReferences = new Set(savedProject ? projectAssetReferences(savedProject.data).map(assetReferenceKey) : []);
  const draftReferences = new Set(project ? projectAssetReferences(project.data).map(assetReferenceKey) : []);
  const pageAssetStatus = new Map<string, "On page" | "Hidden on page">();
  for (const block of project?.data.content ?? []) {
    if (block.type === "caption") continue;
    const key = assetReferenceKey(block.src);
    if (!block.hidden || !pageAssetStatus.has(key)) pageAssetStatus.set(key, block.hidden ? "Hidden on page" : "On page");
  }
  const library = project?.assets.filter((asset) => asset.name.toLowerCase().includes(libraryQuery.trim().toLowerCase()))
    .sort((first, second) => first.name.localeCompare(second.name)) ?? [];
  const featuredSlug = state?.home.data.centerProject;
  const isFeatured = Boolean(savedProject && savedProject.data.slug === featuredSlug);
  const title = project?.data.title ?? (home ? "Homepage" : "Projects");
  return <main className="studio">
    <header className="studio-masthead">
      <a className="studio-brand" href="/" onClick={(event) => { event.preventDefault(); switchTo("overview"); }}>
        Portfolio Studio<span aria-hidden="true">*</span>
      </a>
      <nav aria-label="Studio navigation">
        <button className="studio-text-button" aria-current={selected === "home" ? undefined : "page"} onClick={() => switchTo("overview")} disabled={busy}>Projects</button>
        <button className="studio-text-button" aria-current={selected === "home" ? "page" : undefined} onClick={() => switchTo("home")} disabled={busy}>Homepage</button>
      </nav>
      <a className="studio-text-button studio-site-link" href={portfolioPreviewUrl} target="_blank" rel="noreferrer">View portfolio <span aria-hidden="true">↗</span></a>
    </header>
    <div className="studio-shell">
      <ProjectIndex projects={projects} selectedId={project?.id} busy={busy} onSelect={(id) => switchTo(`project:${id}`)} />
    <div className="studio-workspace" data-project-editor={project ? true : undefined}>
      {(project || home) && (
        <header className="studio-toolbar">
          {project && <button className="studio-text-button studio-back" onClick={() => switchTo("overview")} disabled={busy}>← All projects</button>}
          <div className="studio-toolbar-actions">
            <span className="studio-save-state" role="status" data-dirty={dirty || undefined}>{dirty ? "Unsaved changes" : "Saved"}</span>
            <button className="studio-text-button" onClick={reload} disabled={busy}>Reload from disk</button>
            <button className="studio-button studio-primary" onClick={save} disabled={busy || !dirty}>{busy ? "Working…" : "Save changes"}</button>
          </div>
        </header>
      )}
      <div className="studio-body">
        <div className="studio-heading">
          <div>
            <h1>{title}</h1>
          </div>
          <div className="studio-heading-actions">
            {savedProject?.data.published && (
              <a className="studio-button" href={`${portfolioPreviewUrl}/${encodeURIComponent(savedProject.data.slug)}`} target="_blank" rel="noreferrer">View saved page <span aria-hidden="true">↗</span></a>
            )}
            {!project && !home && <>
              <button className="studio-text-button" onClick={reload} disabled={busy}>Reload from disk</button>
              <button className="studio-button studio-primary" onClick={newProject} disabled={busy || !state}><span aria-hidden="true">+</span> New project</button>
            </>}
          </div>
        </div>
        {error && !assetToRemove && <div className="studio-message studio-error" role="alert">{error}</div>}
        {notice && <div className="studio-message" role="status">{notice}</div>}
        {!state && !error && <p role="status">Loading your content…</p>}

        {state && !project && !home && <>
          <div className="studio-list-tools">
            <div className="studio-filters" role="group" aria-label="Filter by portfolio visibility">
              {visibilityFilters.map(({ value, label }) => (
                <button className="studio-text-button" key={value} type="button" aria-pressed={visibilityFilter === value} onClick={() => setVisibilityFilter(value)}>
                  {label} <span>{visibilityCounts[value]}</span>
                </button>
              ))}
            </div>
            <label className="studio-search">
              <span aria-hidden="true" />
              <input aria-label="Search projects" type="search" placeholder="Search titles or tags" value={query} onChange={(event) => setQuery(event.target.value)} />
            </label>
          </div>
          <div className="studio-project-grid">
            {filtered.map(({ id, data }) => (
              <button className="studio-project-card" key={id} onClick={() => switchTo(`project:${id}`)} disabled={busy}>
                <div className="studio-card-image"><CoverThumbnail id={id} data={data} card /></div>
                <div className="studio-card-copy">
                  <div className="studio-card-title"><h2>{data.title}</h2><span aria-hidden="true">*</span></div>
                  <div className="studio-card-meta">
                    <span className="studio-card-status" data-featured={data.slug === featuredSlug || undefined}>
                      {data.published ? (data.slug === featuredSlug ? "Featured" : "Visible") : "Hidden"}
                    </span>
                    <span>{data.year}</span>
                  </div>
                  {data.tags.length > 0 && <p>{data.tags.join(" · ")}</p>}
                </div>
              </button>
            ))}
          </div>
          {!filtered.length && <p className="studio-empty">{!searchTerm && visibilityFilter === "hidden" ? "No hidden projects." : "No projects match."}</p>}
        </>}

        {project && <fieldset className="studio-editor" disabled={busy}>
          <nav className="studio-project-tabs" aria-label="Project editor">
            {([ ["page", "Project page"], ["library", "Media library"], ["settings", "Settings"] ] as const).map(([tab, label]) => (
              <button className="studio-text-button" key={tab} type="button" aria-current={projectTab === tab ? "page" : undefined} onClick={() => setProjectTab(tab)}>{label}</button>
            ))}
          </nav>
          {projectTab === "settings" && <>
          <div className="studio-columns"><section className="studio-panel"><h2>Project details</h2>
            <div className="studio-visibility">
              <Field label="Portfolio visibility" hint={isFeatured ? "Choose another featured project in Homepage before hiding this one." : "Hidden projects stay editable in Studio."}>
                <select value={project.data.published ? "visible" : "hidden"} disabled={isFeatured} onChange={(event) => changeProject("published", event.target.value === "visible")}>
                  <option value="visible">Show on portfolio</option>
                  <option value="hidden">Hide from portfolio</option>
                </select>
              </Field>
            </div>
            <div className="studio-fields">
            <Field label="Project title"><input value={project.data.title} onChange={(e) => changeProject("title", e.target.value)} /></Field>
            <Field label="Page URL" hint={`${portfolioPreviewUrl}/${project.data.slug}`}><input value={project.data.slug} onChange={(e) => changeProject("slug", e.target.value)} spellCheck={false} /></Field>
            <Field label="Year"><input type="number" min="1900" max="2200" value={project.data.year} onChange={(e) => changeProject("year", Number(e.target.value))} /></Field>
            <Field label="Homepage order" hint="Smaller numbers appear first in the Index and project navigation."><input type="number" min="0" value={project.data.homeOrder} onChange={(e) => changeProject("homeOrder", Number(e.target.value))} /></Field>
            <Field label="Grid tile size"><select value={project.data.gridSize} onChange={(e) => changeProject("gridSize", e.target.value)}>{["L", "M", "S"].map((size) => <option key={size}>{size}</option>)}</select></Field>
            <Field label="Project page layout"><select value={project.data.layout ?? "carousel"} onChange={(e) => changeProject("layout", e.target.value)}><option value="carousel">Horizontal carousel</option><option value="split-stack">Captions left / media stack right</option></select></Field>
          </div>
          <Field label="Tags" hint="Separate tags with commas."><input value={Array.isArray(project.data.tags) ? project.data.tags.join(", ") : ""} onChange={(e) => changeProject("tags", e.target.value.split(",").map((tag) => tag.trimStart()))} onBlur={() => changeProject("tags", project.data.tags.map((tag) => tag.trim()).filter(Boolean))} /></Field>
          </section>
          <section className="studio-panel">
            <h2>Homepage cover</h2>
            <div className="studio-cover"><CoverThumbnail id={project.id} data={project.data} /></div>
            <Field label="Choose an existing image or video">
              <select value={project.data.cover} onChange={(e) => changeProject("cover", e.target.value)}>
                <option value="">Select a cover…</option>
                {project.assets.map((asset) => <option key={asset.src} value={asset.src}>{asset.name}</option>)}
              </select>
            </Field>
            <FileUploadButton label={project.data.cover ? "Replace cover" : "Upload a cover"} accept={libraryFileTypes} className="studio-cover-upload" onSelect={(file) => void upload([file], "cover")} />
            <Field label="Cover description" hint="A short visual description for accessibility."><input value={project.data.coverAlt} onChange={(e) => changeProject("coverAlt", e.target.value)} /></Field>
          </section></div>
          <section className="studio-panel"><h2>Project colors</h2><label className="studio-check"><input type="checkbox" checked={project.data.customColors} onChange={(e) => changeProject("customColors", e.target.checked)} /> Use custom colors for this project</label>{project.data.customColors && <Colors data={project.data} change={changeProject} />}</section>
          </>}
          {projectTab === "library" && <section className="studio-panel" aria-labelledby="studio-library-heading">
            <div className="studio-section-heading studio-library-tools">
              <h2 id="studio-library-heading">Media library <span>{project.assets.length}</span></h2>
              <div className="studio-block-actions">
                <input className="studio-library-search" aria-label="Search library files" type="search" placeholder="Find a file" value={libraryQuery} onChange={(event) => setLibraryQuery(event.target.value)} />
                <label className="studio-upload studio-primary">+ Upload files<input type="file" aria-label="Upload files to library" multiple accept={libraryFileTypes} onChange={(event) => { void upload(Array.from(event.currentTarget.files ?? [])); event.currentTarget.value = ""; }} /></label>
              </div>
            </div>
            {!library.length && <p className="studio-empty">{libraryQuery.trim() ? "No files match." : "Upload files to start this project's library."}</p>}
            <ul className="studio-library-grid">
              {library.map((asset) => {
                const key = assetReferenceKey(asset.src);
                const pageStatus = pageAssetStatus.get(key);
                const inDraft = draftReferences.has(key);
                const inSaved = savedReferences.has(key);
                return (
                  <li className="studio-library-item" key={asset.src}>
                    <div className="studio-library-image"><Thumbnail id={project.id} src={asset.src} type={asset.type} alt={asset.name} controls={false} /></div>
                    <div className="studio-library-name" title={asset.name}>{asset.name}</div>
                    <div className="studio-library-actions">
                      <button className="studio-text-button" type="button" aria-label={`Add ${asset.name} to page`} onClick={() => addAsset(asset)}>{pageStatus ? "+ Add again" : "+ Add to page"}</button>
                      {inDraft || inSaved ? (
                        <span className="studio-library-status">{pageStatus ?? (inDraft ? "Used in cover or poster" : "Save page to remove")}</span>
                      ) : <button className="studio-text-button" type="button" aria-label={`Remove ${asset.name} from library`} onClick={() => { setError(""); setAssetToRemove(asset); }}>Remove</button>}
                    </div>
                  </li>
                );
              })}
            </ul>
          </section>}
          {projectTab === "page" && <section className="studio-panel" aria-labelledby="studio-block-heading">
            <div className="studio-section-heading">
              <div><h2 id="studio-block-heading">Project blocks <span>{project.data.content.length}</span></h2><p>Drag a handle or use the arrows to change the reading order.</p></div>
              <div className="studio-block-actions">
                <button className="studio-button" type="button" onClick={addCaption}>+ Caption</button>
                <button className="studio-button" type="button" onClick={() => setProjectTab("library")}>+ Media from library</button>
              </div>
            </div>
            <div className="studio-visually-hidden" role="status">{blockAnnouncement}</div>
            {!project.data.content.length && <p className="studio-empty">Add a media or caption block to start the page.</p>}
            <ol className="studio-block-list">
              {project.data.content.map((item, index) => {
                const position = index + 1;
                const isCaption = item.type === "caption";
                const name = `${isCaption ? "caption" : "media"} block ${position}`;
                return (
                  <li
                    className="studio-block"
                    data-type={item.type}
                    data-hidden={!isCaption && item.hidden || undefined}
                    data-dragging={drag?.from === index || undefined}
                    data-drop={drag?.to === index ? drag.edge : undefined}
                    key={item.id}
                    onDragOver={(event) => dragOverBlock(event, index)}
                    onDrop={(event) => dropBlock(event, index)}
                  >
                    <div className="studio-block-header">
                      <div className="studio-block-name">
                        <span
                          aria-hidden="true"
                          className="studio-drag-handle"
                          draggable={!busy}
                          title="Drag to reorder"
                          onDragStart={(event) => {
                            event.dataTransfer.effectAllowed = "move";
                            event.dataTransfer.setData("text/plain", String(position));
                            setDrag({ from: index });
                          }}
                          onDragEnd={() => setDrag(null)}
                        >⠿</span>
                        <h3><span>{String(position).padStart(2, "0")}</span> {isCaption ? "Caption" : `Media / ${item.type}`}</h3>
                        {!isCaption && item.hidden && <span className="studio-block-status">Hidden</span>}
                      </div>
                      <div className="studio-block-actions">
                        <button className="studio-button studio-move" type="button" disabled={index === 0} aria-label={`Move ${name} up`} onClick={(event) => moveWithButton(index, -1, event.currentTarget)}>↑</button>
                        <button className="studio-button studio-move" type="button" disabled={position === project.data.content.length} aria-label={`Move ${name} down`} onClick={(event) => moveWithButton(index, 1, event.currentTarget)}>↓</button>
                        {!isCaption && <button className="studio-button" type="button" aria-label={`${item.hidden ? "Show" : "Hide"} ${name} on the project page`} onClick={() => changeBlock(index, "hidden", !item.hidden)}>{item.hidden ? "Show" : "Hide"}</button>}
                        <button className="studio-button" type="button" aria-label={`Remove ${name} from page`} onClick={() => removeBlock(index)}>Remove</button>
                      </div>
                    </div>
                    {isCaption ? (
                      <div className="studio-caption-form">
                        <Field label="Caption label (optional)"><input value={item.label ?? ""} onChange={(e) => changeBlock(index, "label", e.target.value)} /></Field>
                        <Field label="Caption text"><textarea id={`caption-text-${item.id}`} rows={4} value={item.text ?? ""} onChange={(e) => changeBlock(index, "text", e.target.value)} /></Field>
                      </div>
                    ) : (
                      <div className="studio-media">
                        <div className="studio-media-preview"><Thumbnail id={project.id} src={item.src} type={item.type} alt={item.alt} poster={item.poster} /></div>
                        <div className="studio-media-fields">
                          <Field label="Media file"><select value={item.src} onChange={(event) => changeBlock(index, "src", event.target.value)}>{project.assets.filter((asset) => asset.type === item.type).map((asset) => <option key={asset.src} value={asset.src}>{asset.name}</option>)}</select></Field>
                          <Field label="Media description"><input value={item.alt ?? ""} onChange={(e) => changeBlock(index, "alt", e.target.value)} /></Field>
                          <Field label="Aspect ratio"><select value={item.aspectRatio ?? "Default"} onChange={(e) => changeBlock(index, "aspectRatio", e.target.value)}>{ratios.map((ratio) => <option key={ratio} value={ratio}>{ratio === "Default" ? "Default — original proportions" : ratio}</option>)}</select></Field>
                          {project.data.layout === "split-stack" && <Field label="Placement in right column"><select value={item.placement ?? "full"} onChange={(e) => changeBlock(index, "placement", e.target.value)}>{placements.map((placement) => <option key={placement} value={placement}>{placement === "full" ? "Full width" : `Inset — ${placement}`}</option>)}</select></Field>}
                          {item.type === "video" && <>
                            <Field label="Video poster (optional)"><select value={item.poster ?? ""} onChange={(e) => changeBlock(index, "poster", e.target.value)}><option value="">No poster</option>{project.assets.filter((a) => a.type === "image").map((a) => <option value={a.src} key={a.src}>{a.name}</option>)}</select></Field>
                            <VideoSyncField video={item} content={project.data.content} index={index} onChange={(partner) => changeVideoPartner(index, partner)} onPreview={setVideoPreview} />
                          </>}
                        </div>
                      </div>
                    )}
                  </li>
                );
              })}
            </ol>
          </section>}
        </fieldset>}

        {home && state && <fieldset className="studio-editor" disabled={busy}>
          <section className="studio-panel"><h2>Introduction and navigation</h2><Field label="Introduction"><textarea rows={3} value={home.data.intro} onChange={(e) => changeHome("intro", e.target.value)} /></Field><div className="studio-fields"><Field label="Work button label"><input value={home.data.workLabel} onChange={(e) => changeHome("workLabel", e.target.value)} /></Field><Field label="About button label"><input value={home.data.aboutLabel} onChange={(e) => changeHome("aboutLabel", e.target.value)} /></Field><Field label="Default view"><select value={home.data.defaultView} onChange={(e) => changeHome("defaultView", e.target.value)}><option value="grid">Grid</option><option value="index">Index</option></select></Field><Field label="Center / featured project"><select value={home.data.centerProject} onChange={(e) => changeHome("centerProject", e.target.value)}>{state.projects.filter((p) => p.data.published).map((p) => <option key={p.id} value={p.data.slug}>{p.data.title}</option>)}</select></Field></div></section>
          <section className="studio-panel"><h2>Homepage colors</h2><Colors data={home.data} change={changeHome} /></section>
          <section className="studio-panel"><h2>Global project page colors</h2><p>Applied to every project unless custom colors are enabled on that project.</p><Colors data={home.data} prefix="projectPage" change={changeHome} /></section>
        </fieldset>}
      </div>
    </div>
    </div>
    {videoPreview && project && <VideoPairPreview projectId={project.id} pair={videoPreview} onClose={() => setVideoPreview(null)} />}
    {assetToRemove && <dialog ref={removalDialogRef} className="studio-modal" aria-labelledby="studio-remove-asset-title" onCancel={(event) => { event.preventDefault(); if (!busy) setAssetToRemove(null); }}>
      <h2 id="studio-remove-asset-title">Remove from library?</h2>
      <p>{assetToRemove.name} will be moved to Studio’s local backups.</p>
      {error && <p role="alert" className="studio-error">{error}</p>}
      <div className="studio-modal-actions">
        <button className="studio-text-button" type="button" autoFocus disabled={busy} onClick={() => { setAssetToRemove(null); setError(""); }}>Cancel</button>
        <button className="studio-button studio-primary" type="button" disabled={busy} onClick={removeAsset}>{busy ? "Removing…" : "Remove file"}</button>
      </div>
    </dialog>}
    {creating && <dialog ref={dialogRef} className="studio-modal" aria-labelledby="studio-new-title" onCancel={(event) => { event.preventDefault(); if (!busy) setCreating(false); }}><h2 id="studio-new-title">New project</h2><p>New projects are hidden by default.</p>
      {error && <p role="alert" className="studio-error">{error}</p>}
      <form onSubmit={(e) => { e.preventDefault(); void create(); }}><fieldset disabled={busy}><Field label="Project title"><input autoFocus required value={newTitle} onChange={(e) => { setNewTitle(e.target.value); if (!slugEdited) setNewSlug(e.target.value.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "")); }} /></Field><Field label="Page URL" hint={`${portfolioPreviewUrl}/${newSlug || "your-project"}`}><input required pattern="[a-z0-9]+(-[a-z0-9]+)*" maxLength={80} value={newSlug} onChange={(e) => { setNewSlug(e.target.value); setSlugEdited(true); }} /></Field><div className="studio-modal-actions"><button type="button" className="studio-button" onClick={() => { setCreating(false); setError(""); }}>Cancel</button><button className="studio-button studio-primary" type="submit">{busy ? "Creating…" : "Create draft"}</button></div></fieldset></form>
    </dialog>}
  </main>;
}
